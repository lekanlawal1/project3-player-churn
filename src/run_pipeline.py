"""One-command pipeline: raw CSVs → DuckDB → clean → SQL features → models.

    python src/run_pipeline.py

Each stage returns decision-log lines; this orchestrator writes them into
docs/cleaning_log.md so the log always matches the code that actually ran
(same generated-log pattern as Project 1).
"""

from datetime import date
from pathlib import Path

import clean
import export_dashboard
import ingest
import sql_transform
import train

ROOT = Path(__file__).resolve().parent.parent
LOG = ROOT / "docs" / "cleaning_log.md"

STAGES = [("Ingest", ingest), ("Clean", clean),
          ("SQL transform", sql_transform), ("Model", train),
          ("Dashboard export", export_dashboard)]


def main():
    sections = []
    for name, module in STAGES:
        print(f"=== {name} ===")
        lines = module.run()
        print("\n".join(lines) + "\n")
        sections.append((name, lines))

    LOG.parent.mkdir(exist_ok=True)
    doc = [f"# Pipeline Decision Log", "",
           f"Generated by `src/run_pipeline.py` on {date.today()}. "
           "Each entry: what was done — and why. Regenerating the pipeline regenerates this file; "
           "the log cannot drift from the code.", ""]
    for name, lines in sections:
        doc += [f"## {name}", ""] + [f"- {ln}" for ln in lines] + [""]
    LOG.write_text("\n".join(doc), encoding="utf-8")
    print(f"Decision log written to {LOG}")


if __name__ == "__main__":
    main()
